#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const projection = JSON.parse(readFileSync(join(APP, "data/public-products.json"), "utf8"));
const state = projection.projection ?? {};
const publicationAllowed = Boolean(state.publication_allowed);
const quarantine = Boolean(state.quarantine);
const mode = String(state.mode ?? (publicationAllowed && !quarantine ? "approved-commerce" : "informational-fail-closed"));

const outDir = join(APP, "src/generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, "publicationState.ts"),
  `// Generated by scripts/generate-publication-state.mjs. Do not hand-edit build output.\nexport const PUBLICATION_STATE = ${JSON.stringify({ publicationAllowed, quarantine, mode }, null, 2)} as const;\n`,
  "utf8",
);
console.log(`[publication-state] ${mode}; allowed=${publicationAllowed}; quarantine=${quarantine}`);

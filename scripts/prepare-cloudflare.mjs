#!/usr/bin/env node
// Prepares the Cloudflare Pages deployment artifact after `pnpm run build`:
// 1. Copies the governed concierge runtime assets into functions/api/.
// 2. Generates dist/public/_redirects from artifacts/aips-landing/vercel.json
//    redirects plus the committed SPA fallback (kept last — first match wins).
// 3. Generates dist/public/_headers from artifacts/aips-landing/vercel.json
//    headers (Pages glob syntax), with an /api/* rule that keeps function
//    responses free of the static catch-all cache headers.
import { readFileSync, writeFileSync, copyFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const APP = join(REPO, "artifacts/aips-landing");
const DIST = join(APP, "dist/public");
const FUNC_API = join(REPO, "functions/api");

const fail = (msg) => {
  console.error(`[cloudflare-prep] ${msg}`);
  process.exit(1);
};

if (!existsSync(DIST)) fail(`missing ${DIST}; run the app build first`);
if (!existsSync(FUNC_API)) fail(`missing ${FUNC_API}`);

// 1. Governed runtime assets (generated by the build pipeline).
for (const f of ["_policy.json", "_catalog.json"]) {
  const src = join(APP, "api", f);
  if (!existsSync(src)) fail(`missing ${src}; the build must generate it`);
  copyFileSync(src, join(FUNC_API, f));
  console.log(`[cloudflare-prep] copied ${f} -> functions/api/${f}`);
}

// 2. Redirects: vercel.json parity. No SPA splat: not_found_handling =
// "404-page" serves the static 404.html for unmatched routes, which keeps
// genuine 404s from resolving to a 200 SPA shell.
const vercel = JSON.parse(readFileSync(join(APP, "vercel.json"), "utf8"));
const redirectLines = (vercel.redirects ?? []).map(
  (r) => `${r.source}  ${r.destination}  ${r.permanent ? 301 : 302}`,
);
writeFileSync(join(DIST, "_redirects"), `${redirectLines.join("\n")}\n`, "utf8");
console.log(`[cloudflare-prep] wrote _redirects (${redirectLines.length} vercel redirects)`);

// 3. Headers: vercel.json parity in Pages glob syntax.
function pagesGlobs(pattern) {
  if (pattern === "/(.*)") return ["/*"];
  if (pattern === "/assets/(.*)") return ["/assets/*"];
  const image = pattern.match(/^\/\(\.\*\)\\\.\((.*)\)$/);
  if (image) return image[1].split("|").map((ext) => `/*.${ext}`);
  fail(`unexpected header pattern "${pattern}" — convert it manually in scripts/prepare-cloudflare.mjs`);
}

const headerBlocks = [
  {
    path: "/api/*",
    headers: {
      "X-Content-Type-Options": "nosniff",
      "X-Frame-Options": "DENY",
      "Referrer-Policy": "strict-origin-when-cross-origin",
      "Permissions-Policy": "geolocation=(), microphone=(), camera=()",
      "Strict-Transport-Security": "max-age=31536000; includeSubDomains; preload",
    },
  },
];
for (const block of vercel.headers ?? []) {
  const asObj = {};
  for (const h of block.headers ?? []) asObj[h.key] = h.value;
  for (const glob of pagesGlobs(block.source)) headerBlocks.push({ path: glob, headers: asObj });
}

const headerText =
  headerBlocks
    .map((b) => `${b.path}\n${Object.entries(b.headers).map(([k, v]) => `  ${k}: ${v}`).join("\n")}`)
    .join("\n\n") + "\n";
writeFileSync(join(DIST, "_headers"), headerText, "utf8");
console.log("[cloudflare-prep] wrote _headers");

console.log("[cloudflare-prep] done — deploy with: npx wrangler deploy");
